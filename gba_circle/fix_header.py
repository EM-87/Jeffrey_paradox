    0x88,0x1B,0x77,0x4A,0x5A,0x52,0x97,0x9A,0xFC,0xA7,0x73,0x7E,0x9C,0x1B,0xBD,0x08,
    0x28,0x08,0x14,0xA7,0xFF,0x8B,0x55,0xCA,0x57,0x91,0x85,0x38,0xAF,0xE0,0x28,0x7D,
    0x1D,0x2B,0xC3,0x0E,0xDB,0xA7,0x15,0xEA,0x64,0xA0,0xCB,0x95,0x7B,0xA1,0xE2,0x1F,
